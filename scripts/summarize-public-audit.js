import { readFile, writeFile } from 'node:fs/promises';
const dir = new URL('../data/public-audit-2026-10-09/',import.meta.url);
const load=async name=>JSON.parse(await readFile(new URL(name+'.json',dir),'utf8'));
const out={};
for(const name of ['geoffVersion','pondVersion','stackRoot','stackHealth','stackModels','mcp','trixGate','productionHealth'])out[name]=await load(name);
const prod=await load('productionStatus');
out.productionKeys=Object.keys(prod);
const snap=prod.latest||prod.snapshot||prod;
out.production={takenAt:snap.takenAt,keys:Object.keys(snap),sourceCount:Object.keys(snap.sources||{}).length,sources:Object.entries(snap.sources||{}).map(([name,s])=>({name,ok:s.ok,stale:s.stale,status:s.status,checkedAt:s.checkedAt,dataUpdatedAt:s.dataUpdatedAt,reason:s.reason}))};
const boxes=await load('boxes');
out.boxes=Object.fromEntries(Object.entries(boxes).filter(([k,v])=>!Array.isArray(v)));
out.boxArrays=Object.fromEntries(Object.entries(boxes).filter(([k,v])=>Array.isArray(v)).map(([k,v])=>[k,{count:v.length,first:v[0]}]));
const archive=await load('miningArchive');out.miningArchive=archive.summary;
const names=await load('dibziNames'),config=await load('dibziConfig');
const now=config.flashSale.serverNow;
const open=names.filter(x=>Number(x.endsAt)>now);
out.dibzi={config,siteClock:new Date(now).toISOString(),localClock:new Date().toISOString(),total:names.length,open:open.length,openByLocalClock:names.filter(x=>Number(x.endsAt)>Date.now()).length,morphed:names.filter(x=>x.morphed===true).length,cheapest:open.sort((a,b)=>Number(a.amount)-Number(b.amount)).slice(0,5).map(x=>({name:x.name,amount:x.amount,endsAt:x.endsAt,bidCount:x.bidCount}))};
const contract=await load('simContract');
out.simContract={name:contract.name,verified:contract.is_verified,compiler:contract.compiler_version,keys:Object.keys(contract),functions:(contract.abi||[]).filter(x=>x.type==='function').map(x=>({name:x.name,stateMutability:x.stateMutability}))};
await writeFile(new URL('SimulationTypes.sol',dir),contract.source_code||'');
out.contractHintMatches=(contract.source_code||'').split('\n').map((line,i)=>({line:i+1,text:line})).filter(x=>/4500|4_500|8000|8_000|6000|6_000|totalSupply|collapseFee|function collapse|onlyOwner/.test(x.text));
out.zen=(await load('zen')).data?.map(x=>x.id);
out.x402=await load('x402');
await writeFile(new URL('summary.json',dir),JSON.stringify(out,null,2));
console.log(JSON.stringify(out,null,2));
